import type { VehicleDef, VehicleKind } from '@/gameplay/types';
import type { VehiclePhysicsDef } from '@/gameplay/vehicle/VehicleDynamicsTypes';
import { TextureKeys } from '@/config/AssetKeys';

type VehiclePhysicsOverrides = Partial<
  Omit<VehiclePhysicsDef, 'mass' | 'rotationalInertia'>
>;

/** Build a rectangular rigid-body profile from explicit catalogue mass and dimensions. */
function vehiclePhysics(
  mass: number,
  width: number,
  height: number,
  overrides: VehiclePhysicsOverrides = {},
): VehiclePhysicsDef {
  return {
    mass,
    rotationalInertia: (mass * (width * width + height * height)) / 12,
    restitution: overrides.restitution ?? 0.14,
    tireFriction: overrides.tireFriction ?? 0.72,
    lateralGrip: overrides.lateralGrip ?? 0.82,
    rollingResistance: overrides.rollingResistance ?? 1.45,
    lateralDamping: overrides.lateralDamping ?? 3.25,
    angularDamping: overrides.angularDamping ?? 3.1,
    collisionDamageMultiplier: overrides.collisionDamageMultiplier ?? 1,
    minimumImpactSpeed: overrides.minimumImpactSpeed ?? 24,
    maximumCollisionImpulse: overrides.maximumCollisionImpulse ?? mass * 260,
    maximumAngularVelocity: overrides.maximumAngularVelocity ?? 2.4,
  };
}

